// Command pygen generates the supported, deliberately small OpenAPI client subset.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"gopkg.in/yaml.v3"
)

type schema struct {
	Ref                  string            `yaml:"$ref"`
	Type                 string            `yaml:"type"`
	AdditionalProperties *bool             `yaml:"additionalProperties"`
	Required             []string          `yaml:"required"`
	Properties           map[string]schema `yaml:"properties"`
}
type response struct {
	Description string `yaml:"description"`
	Content     map[string]struct {
		Schema schema `yaml:"schema"`
	} `yaml:"content"`
}
type operation struct {
	ID          string `yaml:"operationId"`
	Summary     string `yaml:"summary"`
	RequestBody *struct {
		Required bool `yaml:"required"`
		Content  map[string]struct {
			Schema schema `yaml:"schema"`
		} `yaml:"content"`
	} `yaml:"requestBody"`
	Security  []map[string][]string `yaml:"security"`
	Responses map[string]response   `yaml:"responses"`
}
type document struct {
	OpenAPI string `yaml:"openapi"`
	Info    struct {
		Title   string `yaml:"title"`
		Version string `yaml:"version"`
	} `yaml:"info"`
	Paths      map[string]map[string]operation `yaml:"paths"`
	Components struct {
		SecuritySchemes map[string]struct {
			Type string `yaml:"type"`
			In   string `yaml:"in"`
			Name string `yaml:"name"`
		} `yaml:"securitySchemes"`
		Schemas map[string]schema `yaml:"schemas"`
	} `yaml:"components"`
}

var identifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func validName(s string) bool {
	return identifier.MatchString(s) && !strings.Contains(" False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case self ", " "+s+" ") && !strings.HasPrefix(s, "_")
}
func keys[T any](m map[string]T) []string {
	k := make([]string, 0, len(m))
	for s := range m {
		k = append(k, s)
	}
	sort.Strings(k)
	return k
}

const schemaPrefix = "#/components/schemas/"

// fieldType maps a property schema to a Python type: a primitive, or a model name for a $ref.
func fieldType(s schema, models map[string]schema) (string, error) {
	if s.Ref != "" {
		name := strings.TrimPrefix(s.Ref, schemaPrefix)
		if s.Ref != schemaPrefix+name || s.Type != "" || s.Properties != nil || s.Required != nil || s.AdditionalProperties != nil {
			return "", fmt.Errorf("unsupported property schema")
		}
		if _, ok := models[name]; !ok {
			return "", fmt.Errorf("unknown model %q", name)
		}
		return name, nil
	}
	if s.Properties != nil || s.Required != nil || s.AdditionalProperties != nil {
		return "", fmt.Errorf("unsupported property schema")
	}
	switch s.Type {
	case "string":
		return "str", nil
	case "integer":
		return "int", nil
	case "boolean":
		return "bool", nil
	}
	return "", fmt.Errorf("unsupported property type %q", s.Type)
}
func generate(data []byte) ([]byte, error) {
	var d document
	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)
	if err := dec.Decode(&d); err != nil {
		return nil, err
	}
	if err := dec.Decode(new(any)); err != io.EOF {
		return nil, fmt.Errorf("expected a single YAML document")
	}
	doc, err := openapi3.NewLoader().LoadFromData(data)
	if err != nil {
		return nil, err
	}
	if err := doc.Validate(context.Background()); err != nil {
		return nil, err
	}
	if d.OpenAPI != "3.0.3" {
		return nil, fmt.Errorf("unsupported OpenAPI version")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by pygen; DO NOT EDIT.\n# Spec SHA256: %x\n", sha256.Sum256(data))
	b.WriteString(preamble)
	// Models without $ref fields first, so a model's field types exist when its class is built.
	var plain, nested []string
	for _, name := range keys(d.Components.Schemas) {
		s := d.Components.Schemas[name]
		if !validName(name) || strings.Contains(" Client ProblemError dataclass fields is_dataclass asdict CookieJar json Optional Union get_args get_origin HTTPError Request urlopen str int bool type dict isinstance super float ValueError Exception ", " "+name+" ") || s.Type != "object" || s.Ref != "" || s.AdditionalProperties == nil || *s.AdditionalProperties || len(s.Properties) == 0 {
			return nil, fmt.Errorf("unsupported model %q", name)
		}
		hasRef := false
		for _, p := range s.Properties {
			hasRef = hasRef || p.Ref != ""
		}
		if hasRef {
			nested = append(nested, name)
		} else {
			plain = append(plain, name)
		}
	}
	for _, name := range append(plain, nested...) {
		s := d.Components.Schemas[name]
		required := map[string]bool{}
		for _, p := range s.Required {
			if _, ok := s.Properties[p]; !ok || required[p] {
				return nil, fmt.Errorf("invalid required field %s", p)
			}
			required[p] = true
		}
		fmt.Fprintf(&b, "\n@dataclass\nclass %s:\n", name)
		for _, req := range []bool{true, false} {
			for _, p := range keys(s.Properties) {
				typ, err := fieldType(s.Properties[p], d.Components.Schemas)
				if err == nil && s.Properties[p].Ref != "" && slices.Contains(nested, typ) {
					err = fmt.Errorf("nested models more than one level deep")
				}
				if err != nil || !validName(p) {
					return nil, fmt.Errorf("unsupported field %s.%s: %v", name, p, err)
				}
				if required[p] != req {
					continue
				}
				if req {
					fmt.Fprintf(&b, "    %s: %s\n", p, typ)
				} else {
					fmt.Fprintf(&b, "    %s: Optional[%s] = None\n", p, typ)
				}
			}
		}
	}
	b.WriteString(clientHead)
	for name, sch := range d.Components.SecuritySchemes {
		if sch.Type != "apiKey" || sch.In != "cookie" || !validName(name) || sch.Name == "" {
			return nil, fmt.Errorf("unsupported security scheme %q", name)
		}
	}
	seen := map[string]bool{}
	for _, path := range keys(d.Paths) {
		if !strings.HasPrefix(path, "/v1/") || strings.ContainsAny(path, "{}?#") {
			return nil, fmt.Errorf("unsupported path %q", path)
		}
		for _, method := range keys(d.Paths[path]) {
			op := d.Paths[path][method]
			if (method != "get" && method != "post") || !validName(op.ID) || strings.Contains(" timeout base_url cookies headers ", " "+op.ID+" ") || seen[op.ID] || len(op.Responses) < 2 {
				return nil, fmt.Errorf("unsupported operation %q", op.ID)
			}
			seen[op.ID] = true
			for _, req := range op.Security {
				for scheme, scopes := range req {
					if _, ok := d.Components.SecuritySchemes[scheme]; !ok || len(scopes) != 0 {
						return nil, fmt.Errorf("unsupported security requirement in %q", op.ID)
					}
				}
			}
			param, bodyArg := "", ""
			if rb := op.RequestBody; rb != nil {
				c, ok := rb.Content["application/json"]
				ref := strings.TrimPrefix(c.Schema.Ref, schemaPrefix)
				if method != "post" || !rb.Required || !ok || len(rb.Content) != 1 || c.Schema.Ref != schemaPrefix+ref || c.Schema.Type != "" || c.Schema.Properties != nil || c.Schema.Required != nil || c.Schema.AdditionalProperties != nil {
					return nil, fmt.Errorf("unsupported request body")
				}
				if _, ok := d.Components.Schemas[ref]; !ok {
					return nil, fmt.Errorf("unknown request model")
				}
				param, bodyArg = ", body: "+ref, ", body"
			}
			model, success := "", false
			for _, status := range keys(op.Responses) {
				r := op.Responses[status]
				switch status {
				case "200", "401", "403", "503":
					media := "application/json"
					if status != "200" {
						media = "application/problem+json"
					}
					c, ok := r.Content[media]
					ref := strings.TrimPrefix(c.Schema.Ref, schemaPrefix)
					if !ok || len(r.Content) != 1 || c.Schema.Ref != schemaPrefix+ref || c.Schema.Type != "" || c.Schema.Properties != nil || c.Schema.Required != nil || c.Schema.AdditionalProperties != nil {
						return nil, fmt.Errorf("unsupported response schema")
					}
					if _, ok := d.Components.Schemas[ref]; !ok {
						return nil, fmt.Errorf("unknown response model")
					}
					if status == "200" {
						model, success = ref, true
					} else if ref != "Problem" {
						return nil, fmt.Errorf("error response must reference Problem")
					}
				case "204":
					if len(r.Content) != 0 || success {
						return nil, fmt.Errorf("unsupported response schema")
					}
					success = true
				default:
					return nil, fmt.Errorf("unsupported response %s", status)
				}
			}
			if !success {
				return nil, fmt.Errorf("missing success response")
			}
			ret, result := "None", "None"
			if model != "" {
				ret, result = model, "_decode("+model+", json.load(response))"
			}
			fmt.Fprintf(&b, "\n    def %s(self%s) -> %s:\n        request = self._request(%q, %q%s)\n        try:\n            with urlopen(request, timeout=self.timeout) as response:\n                self.cookies.extract_cookies(response, request)\n                return %s\n        except HTTPError as error:\n            if error.headers.get_content_type() == 'application/problem+json':\n                with error:\n                    problem = _decode(Problem, json.load(error))\n                raise ProblemError(problem) from error\n            error.close()\n            raise\n", op.ID, param, ret, strings.ToUpper(method), path, bodyArg, result)
		}
	}
	return []byte(b.String()), nil
}

// clientHead opens the Client class: cookies persist across calls, headers (for example
// X-CSRF-Token) are sent with every request.
const clientHead = `
class Client:
    def __init__(self, base_url: str, timeout: float = 5):
        self.base_url = base_url.rstrip('/')
        self.timeout = timeout
        self.cookies = CookieJar()
        self.headers = {}

    def _request(self, method, path, body=None):
        headers = {'Accept': 'application/json, application/problem+json', **self.headers}
        data = None
        if body is not None:
            data = json.dumps(asdict(body)).encode()
            headers['Content-Type'] = 'application/json'
        request = Request(self.base_url + path, data=data, headers=headers, method=method)
        self.cookies.add_cookie_header(request)
        return request
`

const preamble = `from dataclasses import asdict, dataclass, fields, is_dataclass
from http.cookiejar import CookieJar
import json
from typing import Optional, Union, get_args, get_origin
from urllib.error import HTTPError
from urllib.request import Request, urlopen


class ProblemError(Exception):
    def __init__(self, problem):
        self.problem = problem
        super().__init__(problem.title)


def _decode(model, data):
    if not isinstance(data, dict):
        raise ValueError('expected JSON object')
    values = {}
    for field in fields(model):
        optional = get_origin(field.type) is Union
        kind = get_args(field.type)[0] if optional else field.type
        if field.name not in data:
            if optional:
                continue
            raise ValueError('missing field: ' + field.name)
        value = data[field.name]
        if is_dataclass(kind):
            values[field.name] = _decode(kind, value)
            continue
        if type(value) is not kind:
            raise ValueError('invalid field: ' + field.name)
        values[field.name] = value
    return model(**values)

`

func main() {
	spec := flag.String("spec", "api/openapi.yaml", "OpenAPI input")
	out := flag.String("out", "clients/python/omi_board_client/_generated.py", "Python output")
	flag.Parse()
	data, err := os.ReadFile(*spec)
	if err == nil {
		data, err = generate(data)
	}
	if err == nil {
		err = os.WriteFile(*out, data, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
